def _brief(tag: Tag) -> TagBrief:
    return TagBrief(id=tag.id, kind=tag.kind, name=tag.name, color=tag.color)


def _part_out(p: Any, *, ui_collapsed: bool = False) -> NotePartOut:
    """Project a NotePart ORM row to the schema. ``ui_collapsed`` is
    user-scoped state from note_part_ui_state; default false (no row
    materialised means expanded)."""
    return NotePartOut(
        id=p.id,
        note_id=p.note_id,
        ord=p.ord,
        title=getattr(p, "title", None),
        body=p.body or "",
        lang=p.lang,
        merged_from_note_id=p.merged_from_note_id,
        version=p.version,
        ui_collapsed=ui_collapsed,
    )


def _derived_transcript(
    parts: list[NotePartOut] | None,
    explicit: str | None,
) -> str | None:
    """Phase 6 final: ``NoteOut.transcript`` is derived. When the
    caller already has the parts list at hand we join part bodies by
    a blank line; otherwise the caller passes an explicit body
    (single-row paths that didn't bother loading parts). Empty parts
    + no override returns ``None`` so the SPA / clients still see
    null-vs-empty distinguished."""
    if parts is not None and parts:
        return "\n\n".join((p.body or "") for p in parts)
    return explicit


def _out(
    n: Note,
    tags: list[Tag] | None = None,
    primary_task_id: uuid.UUID | None = None,
    derived_task_ids: list[uuid.UUID] | None = None,
    linked_task_count: int = 0,
    parts: list[NotePartOut] | None = None,
    transcript: str | None = None,
) -> NoteOut:
    # docs/adr/0029 P3: ``task_id`` exposed in the API is derived
    # from the typed link table (primary_task_id_for_note). Callers
    # batch-load the map for list endpoints; the single-note path
    # may pass the value explicitly. ``derived_task_ids`` is the full
    # list of tasks generated by the note (derived_from + promoted_from),
    # used by the SPA's "N tasks" chip on the note row.
    # ``linked_task_count`` (task 1e07437e) is the total of typed
    # links across every kind (subject, artifact, derived_from,
    # promoted_from); the chip now reflects this so subject/artifact-
    # only links also surface.
    # Migration 0016: ``project_id`` is derived from the project-kind
    # tag in ``tags`` (junction is the source of truth, like tasks).
    project_id = next(
        (t.id for t in (tags or []) if getattr(t.kind, "value", t.kind) == "project"),
        None,
    )
    return NoteOut(
        id=n.id,
        project_id=project_id,
        task_id=primary_task_id,
        kind=n.kind,
        status=n.status,
        title=n.title,
        # Phase 6 final: ``transcript`` is derived from the parts list
        # when the caller has it loaded; otherwise the caller can
        # pass an explicit value (single-row paths that skipped the
        # parts join). The legacy column is gone in migration 0012.
        transcript=_derived_transcript(parts, transcript),
        summary=n.summary,
        audio_ref=n.audio_ref,
        audio_seconds=n.audio_seconds,
        is_archived=n.is_archived,
        deleted_at=n.deleted_at,
        tags=[_brief(t) for t in (tags or [])],
        version=n.version,
        maturity=n.maturity,
        promoted_at=n.promoted_at,
        derived_task_ids=list(derived_task_ids or []),
        linked_task_count=linked_task_count,
        parts=list(parts or []),
    )


